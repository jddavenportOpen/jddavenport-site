def write_if_changed(path: Path, data: str | bytes, written: list[Path]) -> bool:
    raw = data.encode("utf-8") if isinstance(data, str) else data
    path.parent.mkdir(parents=True, exist_ok=True)
    written.append(path)
    if path.exists() and path.read_bytes() == raw:
        return False
    path.write_bytes(raw)
    return True


def prune_stale(keep: set[Path], quiet: bool) -> list[Path]:
    """Delete generated pages under docs/ that this build no longer produces.

    Only files carrying GENERATED_MARK are candidates, and only under OUT.
    """
    removed = []
    out_real = OUT.resolve()
    for p in sorted(OUT.rglob("index.html")):
        rp = p.resolve()
        if out_real not in rp.parents or rp in keep:
            continue
        try:
            head_txt = p.read_text(encoding="utf-8", errors="replace")[:600]
        except OSError:
            continue
        if GENERATED_MARK not in head_txt:
            continue
        p.unlink()
        removed.append(p)
    # remove now-empty directories, deepest first, never OUT itself
    for d in sorted((d for d in OUT.rglob("*") if d.is_dir()), key=lambda d: len(d.parts), reverse=True):
        if d.resolve() != out_real and out_real in d.resolve().parents and not any(d.iterdir()):
            d.rmdir()
    if removed and not quiet:
        for p in removed:
            print(f"  removed stale {p.relative_to(ROOT)}")
    return removed


def update_sitemap(urls: list[tuple[str, str]]) -> bool:
    if not SITEMAP.exists():
        return False
    src = SITEMAP.read_text(encoding="utf-8")
    # drop every existing docs <url> entry, keep everything else byte-for-byte
    pat = re.compile(r"[ \t]*<url>\s*<loc>" + re.escape(SITE) + r"/docs/[^<]*</loc>.*?</url>\s*\n?", re.S)
    kept = pat.sub("", src)
    entries = []
    for url, lastmod in urls:
        pri = "0.8" if url == "/docs/" else "0.7" if url.count("/") == 3 else "0.6"
        entries.append(f"  <url>\n    <loc>{SITE}{url}</loc>\n    <lastmod>{lastmod}</lastmod>\n"
                       f"    <changefreq>monthly</changefreq>\n    <priority>{pri}</priority>\n  </url>\n")
    idx = kept.rfind("</urlset>")
    if idx < 0:
        raise SystemExit("sitemap.xml has no </urlset>")
    new = kept[:idx] + "".join(entries) + kept[idx:]
    if new != src:
        SITEMAP.write_text(new, encoding="utf-8")
        return True
    return False


def build(sections_path: Path, content: Path, quiet: bool = False, sitemap: bool = True) -> int:
    errors: list[str] = []
    warnings: list[str] = []
    sections = load_sections(sections_path)
    load_articles(content, sections, errors, warnings)
    live = [s for s in sections if s.articles]

    ordered = [a for s in live for a in s.ordered()]
    written: list[Path] = []
    changed = 0
    OUT.mkdir(exist_ok=True)

    for asset in ("docs.css", "docs.js"):
        changed += write_if_changed(OUT / asset, (ASSETS / asset).read_bytes(), written)

    changed += write_if_changed(OUT / "index.html", landing_page(sections), written)
    for s in live:
        changed += write_if_changed(OUT / s.id / "index.html", section_page(s, sections), written)
    for k, a in enumerate(ordered):
        prev = ordered[k - 1] if k > 0 else None
        nxt = ordered[k + 1] if k + 1 < len(ordered) else None
        sec = next(s for s in live if s.id == a.section)
        changed += write_if_changed(OUT / a.section / a.slug / "index.html",
                                    article_page(a, sec, sections, prev, nxt), written)

    index = []
    for a in ordered:
        sec = next(s for s in live if s.id == a.section)
        index.append({"title": a.title, "description": a.description, "section": sec.title,
                      "group": a.group, "url": a.url, "headings": a.headings, "text": a.text[:400]})
    for s in live:
        index.append({"title": s.title, "description": s.tier[1], "section": "Section", "group": "",
                      "url": s.url, "headings": [g for g, _ in s.grouped() if g], "text": ""})
    changed += write_if_changed(OUT / "search-index.json",
                                json.dumps(index, ensure_ascii=False, separators=(",", ":")) + "\n", written)

    removed = prune_stale({p.resolve() for p in written}, quiet)

    sm_changed = False
    if sitemap:
        newest = max((a.updated for a in ordered), default="2026-10-05")
        urls = [("/docs/", newest)]
        for s in live:
            urls.append((s.url, max(a.updated for a in s.articles)))
            urls.extend((a.url, a.updated) for a in s.ordered())
        sm_changed = update_sitemap(urls)

    for w in warnings:
        print(f"WARN  {w}", file=sys.stderr)
    for e in errors:
        print(f"ERROR {e}  (skipped)", file=sys.stderr)
    if not quiet:
        print(f"docs: {len(ordered)} articles in {len(live)} sections · {changed} files changed · "
              f"{len(removed)} stale removed · sitemap {'updated' if sm_changed else 'unchanged'} · "
              f"{len(warnings)} warnings · {len(errors)} errors")
    return 1 if errors else 0


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--sections", type=Path, default=DEFAULT_SECTIONS)
    ap.add_argument("--content", type=Path, default=DEFAULT_CONTENT)
    ap.add_argument("--no-sitemap", action="store_true", help="do not touch sitemap.xml")
    ap.add_argument("--quiet", action="store_true")
    args = ap.parse_args()
    return build(args.sections, args.content, quiet=args.quiet, sitemap=not args.no_sitemap)


if __name__ == "__main__":
    sys.exit(main())
