class SourceError(Exception):
    pass


def _parse_scalar(raw: str):
    v = raw.strip()
    if not v:
        return ""
    if v.startswith('"'):
        try:
            return json.loads(v)
        except json.JSONDecodeError as e:
            raise SourceError(f"bad double-quoted value {v!r}: {e}") from None
    if v.startswith("'"):
        if not v.endswith("'") or len(v) < 2:
            raise SourceError(f"unterminated single-quoted value {v!r}")
        return v[1:-1].replace("''", "'")
    if v.startswith("["):
        try:
            return json.loads(v)
        except json.JSONDecodeError:
            inner = v[1:-1] if v.endswith("]") else v[1:]
            items = [p.strip() for p in inner.split(",") if p.strip()]
            return [_parse_scalar(p) if p[0] in "\"'" else p for p in items]
    if re.fullmatch(r"-?\d+", v):
        return int(v)
    return v


def parse_front_matter(text: str):
    """Return (meta dict, body str). Raises SourceError on a malformed file."""
    text = text.replace("\r\n", "\n").lstrip("﻿")
    m = re.match(r"^---\n(.*?)\n---[ \t]*\n?(.*)$", text, re.S)
    if not m:
        raise SourceError("no front matter block (--- ... ---) at top of file")
    meta = {}
    for ln, line in enumerate(m.group(1).split("\n"), 2):
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        km = re.match(r"^([A-Za-z_][\w-]*)\s*:\s*(.*)$", line)
        if not km:
            raise SourceError(f"front matter line {ln} is not 'key: value': {line!r}")
        meta[km.group(1)] = _parse_scalar(km.group(2))
    return meta, m.group(2)


# --------------------------------------------------------------------------
# Markdown subset -> HTML
# --------------------------------------------------------------------------

FENCE_RE = re.compile(r"^(\s*)(`{3,}|~{3,})\s*([\w+#.-]*)\s*$")
HEADING_RE = re.compile(r"^\s{0,3}(#{1,6})\s+(.*?)\s*#*\s*$")
HR_RE = re.compile(r"^\s{0,3}([-*_])(?:\s*\1){2,}\s*$")
LIST_RE = re.compile(r"^(\s*)([-*+]|\d{1,9}[.)])(\s+)(.*)$")
TABLE_SEP_RE = re.compile(r"^\s*\|?\s*:?-{2,}:?\s*(\|\s*:?-{2,}:?\s*)*\|?\s*$")
QUOTE_RE = re.compile(r"^\s{0,3}>\s?(.*)$")
URL_RE = re.compile(r"https?://[^\s<>\"'`]+")


def indent_of(line: str) -> int:
    return len(line) - len(line.lstrip(" "))


def slugify(text: str) -> str:
    s = re.sub(r"<[^>]+>", "", text)
    s = html.unescape(s).lower()
    s = re.sub(r"[`*_\[\]()]", "", s)
    s = re.sub(r"[^a-z0-9]+", "-", s).strip("-")
    return s or "section"


def strip_inline_md(text: str) -> str:
    """Plain text of an inline Markdown string (for ids, TOC, search)."""
    t = re.sub(r"\[([^\]]+)\]\([^)]*\)", r"\1", text)
    t = re.sub(r"\\([\\`*_\[\]|>#-])", r"\1", t)
    t = t.replace("`", "")
    t = re.sub(r"\*\*(.+?)\*\*", r"\1", t)
    t = re.sub(r"(?<![\w*])\*(?!\s)(.+?)(?<!\s)\*(?![\w*])", r"\1", t)
    return t


@dataclass
class RenderCtx:
    ids: dict = field(default_factory=dict)
    toc: list = field(default_factory=list)        # [(level, id, text)]
    links: list = field(default_factory=list)      # every href written
    warnings: list = field(default_factory=list)

    def unique_id(self, base: str) -> str:
        n = self.ids.get(base, 0)
        self.ids[base] = n + 1
        return base if n == 0 else f"{base}-{n + 1}"


def _link_attrs(url: str, ctx: RenderCtx) -> str:
    ctx.links.append(url)
    href = html.escape(url, quote=True)
    if re.match(r"^https?://", url) and not url.startswith(SITE + "/docs"):
        return f'href="{href}" target="_blank" rel="noopener"'
    return f'href="{href}"'


LINK_RE = re.compile(r"\[((?:[^\[\]]|\[[^\[\]]*\])+)\]\(\s*((?:[^()\s]|\([^()\s]*\))+)\s*\)")


def render_inline(text: str, ctx: RenderCtx, allow_links: bool = True) -> str:
    slots: list[str] = []

    def put(s: str) -> str:
        slots.append(s)
        return f"\x00{len(slots) - 1}\x00"

    # 1. backslash escapes
    t = re.sub(r"\\([\\`*_\[\]()|>#!-])", lambda m: put(html.escape(m.group(1))), text)
    # 2. code spans (any run of backticks, matched to an equal run)
    t = re.sub(r"(`+)(.+?)(?<!`)\1(?!`)",
               lambda m: put(f"<code>{html.escape(m.group(2).strip() if m.group(2).strip() else m.group(2))}</code>"), t)
    # 3. links
    if allow_links:
        def link(m):
            label = render_inline(m.group(1), ctx, allow_links=False)
            return put(f"<a {_link_attrs(m.group(2), ctx)}>{label}</a>")
        t = LINK_RE.sub(link, t)

        # 4. bare URLs
        def bare(m):
            url = m.group(0)
            trail = ""
            while url and url[-1] in ".,;:!?*_":
                trail = url[-1] + trail
                url = url[:-1]
            while url.endswith(")") and url.count(")") > url.count("("):
                trail = ")" + trail
                url = url[:-1]
            return put(f"<a {_link_attrs(url, ctx)}>{html.escape(url)}</a>") + trail
        t = URL_RE.sub(bare, t)
    # 5. escape the rest
    t = html.escape(t, quote=False)
    # 6. emphasis
    t = re.sub(r"\*\*(?=\S)(.+?)(?<=\S)\*\*", r"<strong>\1</strong>", t)
    t = re.sub(r"(?<![\w*])\*(?=[^\s*])(.+?)(?<=[^\s*])\*(?![\w*])", r"<em>\1</em>", t)
    # 7. hard line breaks are not part of the contract: soft-wrap lines
    t = t.replace("\n", " ")

    def restore(s: str) -> str:
        return re.sub(r"\x00(\d+)\x00", lambda m: restore(slots[int(m.group(1))]), s)
    return restore(t)


def split_cells(row: str) -> list[str]:
    s = row.strip()
    if s.startswith("|"):
        s = s[1:]
    if s.endswith("|") and not s.endswith("\\|"):
        s = s[:-1]
    cells, cur, in_code, i = [], [], 0, 0
    while i < len(s):
        ch = s[i]
        if ch == "\\" and i + 1 < len(s) and s[i + 1] == "|":
            cur.append("\\|")
            i += 2
            continue
        if ch == "`":
            run = len(s[i:]) - len(s[i:].lstrip("`"))
            if in_code == 0:
                in_code = run
            elif in_code == run:
                in_code = 0
            cur.append("`" * run)
            i += run
            continue
        if ch == "|" and not in_code:
            cells.append("".join(cur).strip())
            cur = []
        else:
            cur.append(ch)
        i += 1
    cells.append("".join(cur).strip())
    return [c.replace("\\|", "|") if "`" in c else c for c in cells]


def is_block_start(line: str) -> bool:
    return bool(FENCE_RE.match(line) or HEADING_RE.match(line) or HR_RE.match(line)
                or QUOTE_RE.match(line) or LIST_RE.match(line))


def code_block(lang: str, code: str) -> str:
    lang = lang.lower()
    cls = f' class="language-{html.escape(lang)}"' if lang else ""
    label = html.escape(lang) if lang else "text"
    return (f'<div class="code-block"><div class="code-bar"><span class="code-lang">{label}</span>'
            f'<button class="copy-btn" type="button" hidden aria-label="Copy code">Copy</button></div>'
            f'<pre><code{cls}>{html.escape(code)}</code></pre></div>')


def render_table(rows: list[str], ctx: RenderCtx) -> str:
    head = split_cells(rows[0])
    aligns = []
    for c in split_cells(rows[1]):
        c = c.strip()
        aligns.append("center" if c.startswith(":") and c.endswith(":") else
                      "right" if c.endswith(":") else "left" if c.startswith(":") else "")
    ncol = len(head)

    def cell(tag, text, idx):
        a = aligns[idx] if idx < len(aligns) else ""
        style = f' style="text-align:{a}"' if a else ""
        return f"<{tag}{style}>{render_inline(text, ctx)}</{tag}>"

    out = [f'<div class="table-wrap" role="region" aria-label="Table" tabindex="0"><table class="cols-{min(ncol, 6)}">',
           "<thead><tr>" + "".join(cell("th", h, i) for i, h in enumerate(head)) + "</tr></thead><tbody>"]
    for r in rows[2:]:
        cells = split_cells(r)
        cells = (cells + [""] * ncol)[:ncol]
        out.append("<tr>" + "".join(cell("td", c, i) for i, c in enumerate(cells)) + "</tr>")
    out.append("</tbody></table></div>")
    return "".join(out)


def render_blocks(lines: list[str], ctx: RenderCtx, depth: int = 0) -> str:
    out: list[str] = []
    i, n = 0, len(lines)
    while i < n:
        line = lines[i]
        if not line.strip():
            i += 1
            continue

        m = FENCE_RE.match(line)
        if m:
            ind, fence, lang = len(m.group(1)), m.group(2), m.group(3)
            close = re.compile(r"^\s*" + re.escape(fence[0]) + "{" + str(len(fence)) + r",}\s*$")
            i += 1
            code = []
            while i < n and not close.match(lines[i]):
                ln = lines[i]
                code.append(ln[min(ind, indent_of(ln)):] if ln.strip() else "")
                i += 1
            if i >= n:
                ctx.warnings.append("unclosed code fence")
            i += 1
            while code and not code[-1].strip():
                code.pop()
            out.append(code_block(lang, "\n".join(code)))
            continue

        m = HEADING_RE.match(line)
        if m:
            level = len(m.group(1))
            text = m.group(2)
            if level == 1:
                ctx.warnings.append(f"'# {text}' heading: the title renders as h1; rendered as h2")
                level = 2
            level = min(level, 4)
            hid = ctx.unique_id(slugify(strip_inline_md(text)))
            inner = render_inline(text, ctx)
            if level in (2, 3) and depth == 0:
                ctx.toc.append((level, hid, strip_inline_md(text)))
            out.append(f'<h{level} id="{hid}"><a class="anchor" href="#{hid}" aria-hidden="true" tabindex="-1">#</a>{inner}</h{level}>')
            i += 1
            continue

        if HR_RE.match(line) and not LIST_RE.match(line):
            out.append("<hr>")
            i += 1
            continue

        if line.lstrip().startswith("|") and i + 1 < n and TABLE_SEP_RE.match(lines[i + 1]):
            rows = [line, lines[i + 1]]
            i += 2
            while i < n and lines[i].strip().startswith("|"):
                rows.append(lines[i])
                i += 1
            out.append(render_table(rows, ctx))
            continue

        if QUOTE_RE.match(line):
            inner = []
            while i < n:
                qm = QUOTE_RE.match(lines[i])
                if qm:
                    inner.append(qm.group(1))
                elif lines[i].strip() and inner and inner[-1].strip() and not is_block_start(lines[i]):
                    inner.append(lines[i].strip())        # lazy continuation
                else:
                    break
                i += 1
            out.append(render_quote(inner, ctx, depth))
            continue

        lm = LIST_RE.match(line)
        if lm:
            html_list, i = render_list(lines, i, ctx, depth)
            out.append(html_list)
            continue

        para = [line.strip()]
        i += 1
        while i < n and lines[i].strip() and not is_block_start(lines[i]) and not (
                lines[i].lstrip().startswith("|") and i + 1 < n and TABLE_SEP_RE.match(lines[i + 1])):
            para.append(lines[i].strip())
            i += 1
        out.append(f"<p>{render_inline(chr(10).join(para), ctx)}</p>")
    return "\n".join(out)


def render_quote(inner: list[str], ctx: RenderCtx, depth: int) -> str:
    first = next((l for l in inner if l.strip()), "")
    cm = re.match(r"^\s*\*\*(" + "|".join(CALLOUTS) + r"):?\*\*:?\s*", first)
    if cm:
        kind = cm.group(1)
        idx = inner.index(first)
        rest = list(inner)
        rest[idx] = first[cm.end():]
        body = render_blocks(rest, ctx, depth + 1)
        return (f'<aside class="callout callout-{kind.lower()}" role="note">'
                f'<p class="callout-label">{kind}</p>{body}</aside>')
    return f"<blockquote>{render_blocks(inner, ctx, depth + 1)}</blockquote>"


def render_list(lines: list[str], i: int, ctx: RenderCtx, depth: int):
    n = len(lines)
    m = LIST_RE.match(lines[i])
    base = len(m.group(1))
    ordered = m.group(2)[0].isdigit()
    start = int(m.group(2)[:-1]) if ordered else 1
    items: list[list[str]] = []

    def sibling(k: int) -> bool:
        mm = LIST_RE.match(lines[k])
        return bool(mm) and indent_of(lines[k]) <= base + 1 and mm.group(2)[0].isdigit() == ordered

    while i < n and sibling(i):
        mm = LIST_RE.match(lines[i])
        content_indent = len(mm.group(1)) + len(mm.group(2)) + min(len(mm.group(3)), 4)
        item = [mm.group(4)]
        i += 1
        while i < n:
            ln = lines[i]
            if not ln.strip():
                j = i
                while j < n and not lines[j].strip():
                    j += 1
                if j < n and indent_of(lines[j]) > base + 1:
                    item.extend([""] * (j - i))     # blank line inside the item
                    i = j
                    continue
                break
            ind = indent_of(ln)
            if ind > base + 1:
                item.append(ln[min(ind, content_indent):])
                i += 1
                continue
            if is_block_start(ln) or (ln.lstrip().startswith("|") and i + 1 < n and TABLE_SEP_RE.match(lines[i + 1])):
                break
            item.append(ln.strip())                  # lazy continuation
            i += 1
        items.append(item)
        # a blank gap followed by another sibling item keeps the list going
        j = i
        while j < n and not lines[j].strip():
            j += 1
        if j < n and j != i and sibling(j):
            i = j

    parts = []
    for item in items:
        if item and (FENCE_RE.match(item[0]) or HEADING_RE.match(item[0]) or QUOTE_RE.match(item[0])
                     or LIST_RE.match(item[0])):
            parts.append(f"<li>{render_blocks(item, ctx, depth + 1)}</li>")
            continue
        k = 0
        while k < len(item) and item[k].strip() and not (k > 0 and is_block_start(item[k])):
            k += 1
        body = render_inline("\n".join(l.strip() for l in item[:k]), ctx)
        if any(r.strip() for r in item[k:]):
            body += render_blocks(item[k:], ctx, depth + 1)
        parts.append(f"<li>{body}</li>")
    tag = "ol" if ordered else "ul"
    st = f' start="{start}"' if ordered and start != 1 else ""
    return f"<{tag}{st}>" + "".join(parts) + f"</{tag}>", i


def markdown_to_html(body: str):
    ctx = RenderCtx()
    lines = body.replace("\r\n", "\n").replace("\t", "    ").split("\n")
    return render_blocks(lines, ctx), ctx


def plain_text(body: str) -> str:
    """Prose text of a Markdown body, for search and reading time."""
    t = re.sub(r"^(\s*)(`{3,}|~{3,}).*?^\s*\2\s*$", " ", body, flags=re.S | re.M)
    t = re.sub(r"^\s*\|?\s*:?-{2,}.*$", " ", t, flags=re.M)
    t = re.sub(r"^\s{0,3}#{1,6}\s+", "", t, flags=re.M)
    t = re.sub(r"^\s*>\s?", "", t, flags=re.M)
    t = re.sub(r"^\s*([-*+]|\d+[.)])\s+", "", t, flags=re.M)
    t = t.replace("|", " ")
    t = strip_inline_md(t)
    return re.sub(r"\s+", " ", t).strip()


