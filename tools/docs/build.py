@dataclass
class Article:
    section: str
    slug: str
    title: str
    description: str
    group: str
    order: int
    updated: str
    src: Path
    body_html: str = ""
    toc: list = field(default_factory=list)
    links: list = field(default_factory=list)
    text: str = ""
    minutes: int = 1
    headings: list = field(default_factory=list)

    @property
    def url(self) -> str:
        return f"/docs/{self.section}/{self.slug}/"


@dataclass
class Section:
    id: str
    title: str
    description: str
    groups: list
    articles: list = field(default_factory=list)
    cta: dict = field(default_factory=dict)

    @property
    def url(self) -> str:
        return f"/docs/{self.id}/"

    def grouped(self):
        """[(group label or '', [articles])] in display order."""
        buckets: dict[str, list] = {}
        for a in self.articles:
            buckets.setdefault(a.group or "", []).append(a)
        order = [""] + list(self.groups) + sorted(g for g in buckets if g and g not in self.groups)
        out = []
        for g in order:
            if g in buckets:
                out.append((g, sorted(buckets[g], key=lambda a: (a.order, a.slug))))
        return out

    def ordered(self):
        return [a for _, arts in self.grouped() for a in arts]

    @property
    def tier(self):
        m = re.match(r"^(Tier \d+)\.\s*(.*)$", self.description)
        return (m.group(1), m.group(2)) if m else ("", self.description)


def load_sections(path: Path) -> list[Section]:
    try:
        data = json.loads(path.read_text())
    except (OSError, json.JSONDecodeError) as e:
        raise SystemExit(f"cannot read sections file {path}: {e}")
    secs, seen = [], set()
    for s in data:
        sid = s["id"]
        if not SLUG_RE.match(sid) or sid in seen:
            raise SystemExit(f"sections.json: bad or duplicate id {sid!r}")
        seen.add(sid)
        secs.append(Section(sid, s["title"], s.get("description", ""), list(s.get("groups") or []), cta=dict(s.get("cta") or {})))
    return secs


def load_articles(content: Path, sections: list[Section], errors: list[str], warnings: list[str]):
    by_id = {s.id: s for s in sections}
    for path in sorted(content.glob("**/*.md")):
        rel = path.relative_to(content)
        try:
            if len(rel.parts) != 2:
                raise SourceError("must live at content/<section>/<slug>.md")
            folder, slug = rel.parts[0], path.stem
            meta, body = parse_front_matter(path.read_text(encoding="utf-8"))
            extra = set(meta) - ALLOWED_KEYS
            if extra:
                raise SourceError(f"unknown front matter keys: {sorted(extra)}")
            missing = [k for k in REQUIRED_KEYS if meta.get(k) in (None, "")]
            if missing:
                raise SourceError(f"missing front matter: {missing}")
            if meta["section"] != folder:
                raise SourceError(f"section {meta['section']!r} does not match folder {folder!r}")
            if folder not in by_id:
                raise SourceError(f"section {folder!r} is not in sections.json")
            if not SLUG_RE.match(slug):
                raise SourceError(f"slug {slug!r} is not lowercase-kebab")
            if not isinstance(meta["order"], int):
                raise SourceError("order must be an integer")
            if not DATE_RE.match(str(meta["updated"])):
                raise SourceError("updated must be YYYY-MM-DD")
            title, desc = str(meta["title"]).strip(), str(meta["description"]).strip()
            if len(desc) >= 160:
                warnings.append(f"{rel}: description is {len(desc)} chars (contract: under 160)")
        except SourceError as e:
            errors.append(f"{rel}: {e}")
            continue
        a = Article(folder, slug, title, desc, str(meta.get("group") or "").strip(),
                    meta["order"], str(meta["updated"]), path)
        a.body_html, ctx = markdown_to_html(body)
        a.toc, a.links = ctx.toc, ctx.links
        for w in ctx.warnings:
            warnings.append(f"{rel}: {w}")
        a.text = plain_text(body)
        a.minutes = max(1, math.ceil(len(a.text.split()) / WORDS_PER_MIN))
        a.headings = [t for lvl, _, t in a.toc]
        sec = by_id[folder]
        if a.group and a.group not in sec.groups:
            warnings.append(f"{rel}: group {a.group!r} is not listed in sections.json for {folder}")
        sec.articles.append(a)


