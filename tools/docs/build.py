#!/usr/bin/env python3
"""Static docs generator for jddavenport.com/docs.

Python 3 standard library only. No pip packages, no build step on Vercel:
run this locally, commit the generated docs/ tree, deploy as usual.

    python3 tools/docs/build.py            # build docs/ + update sitemap.xml
    python3 tools/docs/build.py --quiet
    python3 tools/docs/check.py            # then gate it

Inputs:
    tools/docs/sections.json               ordered [{id,title,description,groups?}]
    tools/docs/content/<section>/<slug>.md front matter + a small Markdown subset

Outputs (everything under docs/ that carries GENERATED_MARK is owned here):
    docs/index.html                        landing
    docs/<section>/index.html              section landing
    docs/<section>/<slug>/index.html       article
    docs/docs.css, docs/docs.js            copied from tools/docs/assets/
    docs/search-index.json                 client-side search index
    sitemap.xml                            docs URLs replaced, other entries kept

The build is deterministic (no timestamps), writes a file only when its bytes
change, and deletes stale pages it generated earlier. It never deletes a file
that lacks GENERATED_MARK and never touches anything outside docs/ except the
docs block of sitemap.xml.
"""
