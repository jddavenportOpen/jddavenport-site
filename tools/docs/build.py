def sidebar(sections: list[Section], cur_section: str, cur_url: str) -> str:
    parts = ['<aside class="docs-sidebar" id="docsSidebar" aria-label="Docs navigation">',
             '<div class="sidebar-inner">',
             '<div class="sidebar-top"><a class="sidebar-home" href="/docs/">Docs home</a>'
             '<button class="drawer-close" type="button" id="drawerClose" aria-label="Close menu"><span aria-hidden="true"></span></button></div>',
             search_box("sidebar"), '<nav class="tree" aria-label="Sections">']
    for s in sections:
        if not s.articles:
            continue
        is_cur = s.id == cur_section
        opn = " open" if is_cur else ""
        parts.append(f'<details class="tree-section"{opn}><summary>{E(s.title)}</summary>')
        ov = ' aria-current="page"' if cur_url == s.url else ""
        parts.append(f'<ul><li><a href="{s.url}"{ov}>Overview</a></li></ul>')
        for g, arts in s.grouped():
            if g:
                parts.append(f'<p class="tree-group">{E(g)}</p>')
            parts.append("<ul>")
            for a in arts:
                c = ' aria-current="page"' if a.url == cur_url else ""
                parts.append(f'<li><a href="{a.url}"{c}>{E(a.title)}</a></li>')
            parts.append("</ul>")
        parts.append("</details>")
    parts.append("</nav></div></aside>")
    return "\n".join(parts)


